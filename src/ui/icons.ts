export type IconName = keyof typeof GLYPHS;

const cache = new Map<string, SVGSVGElement>();

function path(rows: string[]): string {
  let d = '';
  rows.forEach((row, y) => {
    // Merge horizontal runs into one rect each.
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x++; continue; }
      let e = x;
      while (e < row.length && row[e] === '#') e++;
      d += `M${x} ${y}h${e - x}v1h${x - e}z`;
      x = e;
    }
  });
  return d;
}

/** A pixel glyph as an inline SVG (inherits the text colour). */
export function icon(name: IconName, cls = ''): SVGSVGElement {
  let base = cache.get(name);
  if (!base) {
    const t = document.createElement('template');
    t.innerHTML = `<svg class="ic" viewBox="0 0 9 9" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true" focusable="false"><path d="${path(GLYPHS[name])}"/></svg>`;
    base = t.content.firstElementChild as SVGSVGElement;
    cache.set(name, base);
  }
  const el = base.cloneNode(true) as SVGSVGElement;
  if (cls) el.classList.add(...cls.split(' '));
  return el;
}
